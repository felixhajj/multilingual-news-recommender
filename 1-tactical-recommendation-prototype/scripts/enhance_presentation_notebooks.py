from copy import deepcopy
from pathlib import Path

import nbformat
from nbclient import NotebookClient


ROOT = Path(__file__).resolve().parents[1]
NOTEBOOK_DIR = ROOT / "notebooks"
KERNEL_NAME = "python3"
PRESENTATION_TAG = "visible-presentation"


def markdown(source):
    return nbformat.v4.new_markdown_cell(source, metadata={"tags": [PRESENTATION_TAG]})


def code(source):
    return nbformat.v4.new_code_cell(source, metadata={"tags": [PRESENTATION_TAG]})


def execute_notebook(notebook):
    NotebookClient(
        notebook,
        timeout=300,
        kernel_name=KERNEL_NAME,
        resources={"metadata": {"path": str(ROOT)}},
    ).execute()
    return notebook


