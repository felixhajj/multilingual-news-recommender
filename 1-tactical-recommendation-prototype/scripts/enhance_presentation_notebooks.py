def enhance_qlora_notebook():
    path = NOTEBOOK_DIR / "tactical_report_entity_extraction_qlora.ipynb"
    notebook = nbformat.read(path, as_version=4)
    notebook.cells = [
        cell
        for cell in notebook.cells
        if PRESENTATION_TAG not in cell.get("metadata", {}).get("tags", [])
    ]

    proof_notebook = nbformat.v4.new_notebook(
        cells=deepcopy(qlora_fast_proof_cells()),
        metadata=deepcopy(notebook.metadata),
    )
    execute_notebook(proof_notebook)

    notebook.cells[1:1] = proof_notebook.cells
    nbformat.write(notebook, path)


